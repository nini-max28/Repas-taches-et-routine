// Ajoute les notes et les étapes détaillées aux recettes d'une liste (celles qui n'ont pas de détail restent telles quelles).
export function withDetails(list, lang) {
  const details = lang === "en" ? RECIPE_DETAILS_EN : RECIPE_DETAILS_FR;
  return list.map(r => (details[r.title] ? { ...r, ...details[r.title] } : r));
}

// Détail d'une recette suggérée, par titre (insensible aux majuscules), ou null.
export function detailsForTitle(title) {
  const key = String(title || "").trim().toLowerCase();
  for (const table of [RECIPE_DETAILS_FR, RECIPE_DETAILS_EN]) {
    for (const t of Object.keys(table)) if (t.toLowerCase() === key) return table[t];
  }
  return null;
}
